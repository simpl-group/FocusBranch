    net TEXT,
    img INTEGER,
    eps INTEGER,
    starting_level INTEGER,
    use_cvd INTEGER DEFAULT 0,
    estimated_time REAL,
    geometry TEXT,
    PRIMARY KEY (net, img, eps, starting_level, use_cvd)
);

